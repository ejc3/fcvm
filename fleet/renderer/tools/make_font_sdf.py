"""Builds src/font_sdf.h: a signed distance atlas of Inter (SIL OFL 1.1, see
fonts/OFL.txt) for printable ASCII, with advances and kerning.

    python3 tools/make_font_sdf.py INTER_VARIABLE_TTF > src/font_sdf.h

Needs fonttools, pillow, numpy, scipy and uharfbuzz (the build does not: the
header is committed). The variable font is instanced at weight 600, optical
size 32. Each glyph is rendered at 8x the atlas resolution, its exact
Euclidean distance transform taken inside and outside, and the distance at
each atlas texel centre stored as a byte: 128 + d / SPREAD * 127, d in em,
positive outside. Kerning is every pair whose shaped advance (HarfBuzz, with
the font's kern feature) differs from the sum of the two advances.
"""
import base64
import io
import sys

import numpy as np
import uharfbuzz as hb
from fontTools.ttLib import TTFont
from fontTools.varLib import instancer
from PIL import Image, ImageDraw, ImageFont
from scipy.ndimage import distance_transform_edt

PX_PER_EM = 36   # atlas texels per em
OVER = 8         # supersampling of the source render
SPREAD = 0.35    # em: distances are stored out to this far from an edge
ATLAS_W = 1024
CHARS = [chr(c) for c in range(32, 127)]

src = TTFont(sys.argv[1])
inst = instancer.instantiateVariableFont(src, {"wght": 600, "opsz": 32})
buf = io.BytesIO()
inst.save(buf)
data = buf.getvalue()
upem = inst["head"].unitsPerEm

face = hb.Face(data)
font = hb.Font(face)
font.scale = (upem, upem)


def shape(text):
    b = hb.Buffer()
    b.add_str(text)
    b.guess_segment_properties()
    hb.shape(font, b, {"kern": True, "liga": False, "calt": False})
    return [p.x_advance / upem for p in b.glyph_positions]


adv = {c: shape(c)[0] for c in CHARS}
kern = []
for a in CHARS[1:]:
    for b in CHARS[1:]:
        d = shape(a + b)[0] - adv[a]
        if abs(d) > 1e-4:
            kern.append((ord(a), ord(b), d))

size = PX_PER_EM * OVER
pil = ImageFont.truetype(io.BytesIO(data), size)
pad = int(np.ceil(SPREAD * PX_PER_EM)) + 1  # texels around the ink
cells = []
for c in CHARS:
    if c == " ":
        cells.append((c, None, 0, 0))
        continue
    x0, y0, x1, y1 = pil.getbbox(c, anchor="ls")  # ink box, pixels, origin at the baseline
    # the cell, in texels, with its origin at the glyph origin
    tx0, ty0 = int(np.floor(x0 / OVER)) - pad, int(np.floor(y0 / OVER)) - pad
    tx1, ty1 = int(np.ceil(x1 / OVER)) + pad, int(np.ceil(y1 / OVER)) + pad
    W, H = (tx1 - tx0) * OVER, (ty1 - ty0) * OVER
    im = Image.new("L", (W, H), 0)
    ImageDraw.Draw(im).text((-tx0 * OVER, -ty0 * OVER), c, font=pil, fill=255, anchor="ls")
    ink = np.asarray(im) >= 128
    d_out = distance_transform_edt(~ink)
    d_in = distance_transform_edt(ink)
    sd = (d_out - d_in) / (OVER * PX_PER_EM)  # em, positive outside
    # texel centres
    ys = (np.arange(ty1 - ty0) * OVER + OVER // 2)
    xs = (np.arange(tx1 - tx0) * OVER + OVER // 2)
    s = sd[np.ix_(ys, xs)]
    q = np.clip(np.round(128 + s / SPREAD * 127), 0, 255).astype(np.uint8)
    cells.append((c, q, tx0, ty0))

# shelf packing
atlas_rows = []
x = y = shelf_h = 0
place = {}
for c, q, tx0, ty0 in sorted(cells, key=lambda e: -(e[1].shape[0] if e[1] is not None else 0)):
    if q is None:
        continue
    h, w = q.shape
    if x + w > ATLAS_W:
        x, y, shelf_h = 0, y + shelf_h + 1, 0
    place[c] = (x, y)
    x += w + 1
    shelf_h = max(shelf_h, h)
ATLAS_H = y + shelf_h + 1
atlas = np.full((ATLAS_H, ATLAS_W), 255, np.uint8)  # outside
for c, q, tx0, ty0 in cells:
    if q is None:
        continue
    ax, ay = place[c]
    atlas[ay:ay + q.shape[0], ax:ax + q.shape[1]] = q

out = sys.stdout
out.write("// Generated by tools/make_font_sdf.py from Inter (SIL Open Font License 1.1,\n")
out.write("// fleet/renderer/fonts/OFL.txt), weight 600, optical size 32. Do not edit.\n")
out.write("#pragma once\n\n")
out.write(f"#define SDF_ATLAS_W {ATLAS_W}\n#define SDF_ATLAS_H {ATLAS_H}\n")
out.write(f"#define SDF_PX_PER_EM {PX_PER_EM}.0f\n#define SDF_SPREAD {SPREAD}f\n")
cap = inst["OS/2"].sCapHeight / upem
asc = inst["hhea"].ascent / upem
out.write(f"#define SDF_CAP_HEIGHT {cap:.6f}f  // em\n#define SDF_ASCENT {asc:.6f}f\n\n")
out.write("// per character 32..126: advance (em); the cell in the atlas (texels) and\n")
out.write("// its top-left corner relative to the glyph origin on the baseline (texels,\n// y down); 0 size for the space\n")
out.write("struct SdfGlyph {\n  float advance;\n  short ax, ay, w, h, ox, oy;\n};\n")
out.write("static const SdfGlyph kSdfGlyphs[95] = {\n")
for c, q, tx0, ty0 in cells:
    if q is None:
        out.write(f"    {{{adv[c]:.6f}f, 0, 0, 0, 0, 0, 0}},  // ' '\n")
    else:
        ax, ay = place[c]
        h, w = q.shape
        esc = c.replace("\\", "\\\\").replace("'", "\\'")
        out.write(f"    {{{adv[c]:.6f}f, {ax}, {ay}, {w}, {h}, {tx0}, {ty0}}},  // '{esc}'\n")
out.write("};\n\n")
out.write(f"// kerning: (left, right, adjustment in em), sorted\nstatic const int kSdfKernN = {len(kern)};\n")
out.write("struct SdfKern {\n  unsigned char a, b;\n  float d;\n};\nstatic const SdfKern kSdfKern[] = {\n")
for a, b, d in sorted(kern):
    out.write(f"    {{{a}, {b}, {d:.6f}f}},\n")
out.write("};\n\n")
b64 = base64.b64encode(atlas.tobytes()).decode()
out.write("#ifdef SDF_WITH_ATLAS\n")
out.write(f"// the atlas, SDF_ATLAS_W x SDF_ATLAS_H bytes, base64\nstatic const char kSdfAtlasB64[] =\n")
for i in range(0, len(b64), 120):
    out.write(f'    "{b64[i:i + 120]}"\n')
out.write(";\n#endif\n")
sys.stderr.write(f"atlas {ATLAS_W}x{ATLAS_H}, {len(kern)} kerning pairs\n")
