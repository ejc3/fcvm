// Writes core/mirror/table.ts, the wire layout of every GLES 2/3 and renderControl call, from
// the emugen specs gfxstream generates its encoders and decoders from (core/mirror/spec,
// copied from ejc3/gfxstream's codegen/). The GPU mirror (docs/fleet/ARCHITECTURE.md,
// "The GPU mirror") decodes the guest's command stream with it.
//
//   node scripts/gen-mirror-table.ts           write core/mirror/table.ts
//   node scripts/gen-mirror-table.ts --check   exit 1 unless table.ts is what the specs give
//
// emugen's wire layout, from gfxstream's generated decoders: each call is u32 opcode, u32
// packet size, then each parameter in order. A scalar takes its type's width from the
// .types file (GLboolean one byte, GLsync and GLint64 eight). A pointer parameter takes a u32
// byte count, then those bytes when the guest sends them (`in`, the default, and `inout`);
// an `out` pointer sends the count only. A DMA pointer is a u64 guest address, then the u32
// count. A call with an `out` pointer or a return value is answered by one reply: each out
// pointer's bytes in order, then the return value.

import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const here = fileURLToPath(new URL("../core/mirror/", import.meta.url));

interface Spec {
  base: number;
  file: string;
}

function parseTypes(text: string): Map<string, number> {
  const m = new Map<string, number>();
  for (const line of text.split("\n")) {
    const f = line.trim().split(/\s+/);
    if (f.length >= 2 && /^\d+$/.test(f[1]!)) m.set(f[0]!, Number(f[1]) / 8);
  }
  return m;
}

interface Attr {
  dir: Map<string, string>;
  dma: Set<string>;
  len: Map<string, string>;
}

function parseAttrib(text: string): { base: number; attrs: Map<string, Attr> } {
  const attrs = new Map<string, Attr>();
  let cur: Attr | null = null;
  let base = -1;
  for (const raw of text.split("\n")) {
    if (raw.trim().startsWith("#") || raw.trim() === "") continue;
    const f = raw.trim().split(/\s+/);
    if (!/^\s/.test(raw)) {
      if (f[0] === "GLOBAL") {
        cur = null;
        continue;
      }
      // a call can have several blocks: they add up
      cur = attrs.get(f[0]!) ?? { dir: new Map(), dma: new Set(), len: new Map() };
      attrs.set(f[0]!, cur);
      continue;
    }
    if (f[0] === "base_opcode") base = Number(f[1]);
    if (!cur) continue;
    if (f[0] === "dir") cur.dir.set(f[1]!, f[2]!);
    if (f[0] === "var_flag" && f.slice(2).includes("DMA")) cur.dma.add(f[1]!);
    if (f[0] === "len") cur.len.set(f[1]!, f.slice(2).join(" "));
  }
  return { base, attrs };
}

// One parameter on the wire: "s<bytes><kind>" a scalar (u unsigned, i signed, f float), or a
// pointer: "pi" bytes sent, "po" count only, "pio" both directions, "pd" DMA.
function wireOf(type: string, name: string, attr: Attr | undefined, types: Map<string, number>): string {
  const t = type.replace(/\bconst\b/g, "").replace(/\s+/g, "");
  if (t.includes("*") || t.endsWith("_ptr")) {
    if (attr?.dma.has(name)) return "pd";
    const d = attr?.dir.get(name) ?? "in";
    return d === "out" ? "po" : d === "inout" ? "pio" : "pi";
  }
  const bytes = types.get(t) ?? 4;
  const kind = /float|clampf/i.test(t) ? "f" : /^(GLint|GLsizei|GLshort|EGLint|int|GLfixed|GLclampx|GLint64|GLint32)$/.test(t) ? "i" : "u";
  return `s${bytes}${kind}`;
}

function generate(): string {
  const out: string[] = [];
  out.push("// Generated by scripts/gen-mirror-table.ts from core/mirror/spec: do not edit.");
  out.push("// Each call: [name, wire parameters, return value bytes, answered by a reply].");
  out.push("// A wire parameter is \"s<bytes><u|i|f>\" a scalar, or a pointer: \"pi\" the guest's bytes,");
  out.push("// \"po\" a byte count only (the data is in the reply), \"pio\" both, \"pd\" a DMA address.");
  out.push("");
  out.push("export type WireCall = readonly [name: string, params: readonly string[], ret: number, replies: boolean];");
  for (const spec of [
    { base: 2048, file: "gles2" },
    { base: 10000, file: "renderControl" },
  ] satisfies Spec[]) {
    const types = parseTypes(readFileSync(`${here}spec/${spec.file}.types`, "utf8"));
    const { base, attrs } = parseAttrib(readFileSync(`${here}spec/${spec.file}.attrib`, "utf8"));
    if (base !== spec.base) throw new Error(`${spec.file}.attrib: base_opcode ${base}, expected ${spec.base}`);
    const calls: string[] = [];
    for (const line of readFileSync(`${here}spec/${spec.file}.in`, "utf8").split("\n")) {
      const m = /^GL_EN\w+\(\s*([^,)]+?)\s*,\s*(\w+)\s*(?:,(.*))?\)\s*;?\s*$/.exec(line.trim());
      if (!m) continue;
      const [, ret, name, rest] = m;
      const attr = attrs.get(name!);
      const parsed = (rest ?? "")
        .split(",")
        .map((p) => p.trim())
        .filter((p) => p !== "" && p !== "void")
        .map((p) => {
          const pm = /^(.*?)([A-Za-z_]\w*)$/.exec(p);
          if (!pm) throw new Error(`${name}: cannot parse parameter ${p}`);
          return { type: pm[1]!, name: pm[2]! };
        });
      // A DMA pointer's length parameter travels as the pointer's own count, not on its own.
      const merged = new Set([...(attr?.dma ?? [])].map((d) => attr?.len.get(d)).filter((x): x is string => x !== undefined));
      const params = parsed.filter((p) => !merged.has(p.name)).map((p) => wireOf(p.type, p.name, attr, types));
      const retType = ret!.replace(/\s+/g, "");
      const retBytes = retType === "void" ? 0 : (types.get(retType) ?? 4);
      const replies = retBytes > 0 || params.some((p) => p === "po" || p === "pio");
      calls.push(`  [${JSON.stringify(name)}, [${params.map((p) => JSON.stringify(p)).join(", ")}], ${retBytes}, ${replies}],`);
    }
    const id = spec.file === "gles2" ? "GLES2" : "RENDER_CONTROL";
    out.push("");
    out.push(`export const ${id}_BASE = ${spec.base};`);
    out.push(`export const ${id}: readonly WireCall[] = [`);
    out.push(...calls);
    out.push("];");
  }
  return out.join("\n") + "\n";
}

const text = generate();
const target = `${here}table.ts`;
if (process.argv.includes("--check")) {
  const now = readFileSync(target, "utf8");
  if (now !== text) {
    console.error("core/mirror/table.ts is not what core/mirror/spec gives: run node scripts/gen-mirror-table.ts");
    process.exit(1);
  }
} else {
  writeFileSync(target, text);
}
