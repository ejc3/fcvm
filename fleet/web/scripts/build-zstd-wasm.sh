#!/bin/bash
# Builds the GPU mirror's zstd decoder (app/_wall/mirror/zstd/zdec.c) for wasm32 and writes it,
# base64, into app/_wall/mirror/zstd-wasm.ts, which the page's mirror worker loads
# (app/_wall/mirror/zstd.ts). The decoder is zstd's single-file decoder from the pinned release,
# built with no libc. Needs curl, python3, clang with the wasm32 target and wasm-ld
# (CLANG= and WASM_LD= name others).
#
#   scripts/build-zstd-wasm.sh
set -euo pipefail
WEB=$(cd "$(dirname "$0")/.." && pwd)
DIR=$WEB/app/_wall/mirror/zstd
VERSION=1.5.7
SHA256=eb33e51f49a15e023950cd7825ca74a4a2b43db8354825ac24fc1b7ee09e6fa3
CLANG=${CLANG:-clang}
WASM_LD=${WASM_LD:-$(command -v wasm-ld || ls /usr/lib/llvm-*/bin/wasm-ld 2> /dev/null | sort -V | tail -1)}
[ -x "$WASM_LD" ] || { echo "build-zstd-wasm.sh: no wasm-ld (set WASM_LD=)" >&2; exit 2; }
tmp=$(mktemp -d)
trap 'rm -rf "$tmp"' EXIT
curl -fsSL -o "$tmp/zstd.tar.gz" "https://github.com/facebook/zstd/releases/download/v$VERSION/zstd-$VERSION.tar.gz"
echo "$SHA256  $tmp/zstd.tar.gz" | sha256sum -c --quiet
tar -xzf "$tmp/zstd.tar.gz" -C "$tmp"
src=$tmp/zstd-$VERSION
(cd "$src/build/single_file_libs" && python3 combine.py -r ../../lib -x legacy/zstd_legacy.h -o "$tmp/zstddeclib.c" zstddeclib-in.c > /dev/null 2>&1)
cp "$src/lib/zstd.h" "$src/lib/zstd_errors.h" "$tmp/"
cp "$src/LICENSE" "$DIR/LICENSE"
"$CLANG" --target=wasm32 -Os -nostdlib -ffreestanding -mbulk-memory -fvisibility=hidden \
  -I"$DIR/include" -I"$tmp" -fuse-ld="$WASM_LD" -Wl,--no-entry -Wl,--strip-all \
  -o "$tmp/zdec.wasm" "$DIR/zdec.c"
# The sources' digest: core/test/zstd.test.ts fails when they change and this was not rerun.
digest=$(cd "$DIR" && find . -type f ! -name LICENSE -print0 | LC_ALL=C sort -z | xargs -0 sha256sum | sha256sum | cut -c1-64)
{
  echo "// Generated by scripts/build-zstd-wasm.sh: zstd $VERSION's decoder (BSD, app/_wall/mirror/zstd/LICENSE)"
  echo "// with app/_wall/mirror/zstd/zdec.c, built for wasm32. Do not edit; rerun the script."
  echo "export const ZSTD_VERSION = \"$VERSION\";"
  echo "/** sha256 of app/_wall/mirror/zstd's sources this was built from. */"
  echo "export const ZSTD_WASM_SOURCES = \"$digest\";"
  echo "export const ZSTD_WASM_BASE64 ="
  echo "  \"$(base64 -w0 "$tmp/zdec.wasm")\";"
} > "$WEB/app/_wall/mirror/zstd-wasm.ts"
echo "app/_wall/mirror/zstd-wasm.ts: $(stat -c %s "$tmp/zdec.wasm") bytes of wasm, sources $digest"
