/// A restored routed clone must be able to egress the instant it is up.
///
/// Routed guest traffic leaves through the namespace's IPv6 default-route nexthop:
/// the host veth's link-local. IPv6 Duplicate Address Detection used to make that
/// address — and the namespace's own br0 link-local, which has to source the
/// Neighbor Solicitation that resolves it — `tentative` for
/// rand(0..router_solicitation_delay=1s) + dad_transmits(1) x retrans_time_ms(1000).
/// A tentative address neither answers nor can source an NS, so every restored
/// routed clone had NO egress for 1-2s after its veth came up. Cold boots hid it
/// (DAD ran in the shadow of the multi-second guest boot); clones are ready in
/// ~700ms, so it landed on the critical path — measured p50 1,081ms to first
/// connection versus 3ms for every other egress mode.
///
/// The `nodad` assertion (anchored to the exact EUI-64 address fcvm installs) is
/// the deterministic catcher: a kernel-autogenerated link-local never carries that
/// flag, so a regression fails this test every run rather than only when the random
/// DAD delay happens to be long. There is deliberately NO timing assertion: by the
/// time the harness can exec into the clone (health poll + state lookups, ~0.5-1s
/// after the veth came up) the DAD window has already expired, so any wall-clock
/// bound measured from here would pass with the bug present. The in-guest probe at
/// the end is a functional egress check only.
#[cfg(feature = "privileged-tests")]
#[tokio::test]
async fn test_egress_clone_routed_no_dad_stall() -> Result<()> {
    let (baseline_name, clone_name, snapshot_name, _) = common::unique_names("egress-routed-dad");

    println!("\n╔═══════════════════════════════════════════════════════════════╗");
    println!("║     Routed Clone: no DAD stall on restore                     ║");
    println!("╚═══════════════════════════════════════════════════════════════╝\n");

    let test_server = common::LocalTestServer::start_on_available_port("::")
        .await
        .context("starting local test server")?;
    let host_ipv6 = common::get_host_ipv6().await?;
    let port = test_server.port;
    println!("  Host test server: [{}]:{}", host_ipv6, port);

    println!("\nStep 1: Starting baseline VM '{}'...", baseline_name);
    let (_baseline_child, baseline_pid) = common::spawn_fcvm_with_logs(
        &[
            "podman",
            "run",
            "--name",
            &baseline_name,
            "--network",
            "routed",
            common::TEST_IMAGE,
        ],
        &baseline_name,
    )
    .await
    .context("spawning baseline VM")?;
    if let Err(e) = common::poll_health_by_pid(baseline_pid, 300).await {
        test_server.stop().await;
        common::kill_process(baseline_pid).await;
        return Err(e.context("baseline VM failed to become healthy"));
    }
    println!("  ✓ Baseline VM healthy");

    println!("\nStep 2: Creating snapshot '{}'...", snapshot_name);
    let snap = tokio::process::Command::new(common::find_fcvm_binary()?)
        .args([
            "snapshot",
            "create",
            "--pid",
            &baseline_pid.to_string(),
            "--tag",
            &snapshot_name,
        ])
        .output()
        .await
        .context("running snapshot create")?;
    if !snap.status.success() {
        test_server.stop().await;
        common::kill_process(baseline_pid).await;
        anyhow::bail!(
            "snapshot creation failed: {}",
            String::from_utf8_lossy(&snap.stderr)
        );
    }
    common::kill_process(baseline_pid).await;
    println!("  ✓ Snapshot created, baseline killed");

    println!("\nStep 3: Starting memory server...");
    let (_serve_child, serve_pid) =
        common::spawn_fcvm_with_logs(&["snapshot", "serve", &snapshot_name], "uffd-server-dad")
            .await
            .context("spawning memory server")?;
    common::poll_serve_state_by_pid(serve_pid, 30).await?;
    println!("  ✓ Memory server ready (PID: {})", serve_pid);

    println!("\nStep 4: Spawning clone '{}'...", clone_name);
    let (_clone_child, clone_pid) = common::spawn_fcvm_with_logs(
        &[
            "snapshot",
            "run",
            "--pid",
            &serve_pid.to_string(),
            "--name",
            &clone_name,
        ],
        &clone_name,
    )
    .await
    .context("spawning clone")?;
    common::poll_health_by_pid(clone_pid, 120).await?;
    println!("  ✓ Clone is healthy");

    let result = assert_routed_clone_nexthop_nodad_and_egress(clone_pid, &host_ipv6, port).await;

    println!("\nCleaning up...");
    common::kill_process(clone_pid).await;
    common::kill_process(serve_pid).await;
    test_server.stop().await;

    result?;
    println!("\n✅ ROUTED CLONE HAS NO DAD STALL");
    Ok(())
}

/// Assert the clone's IPv6 nexthop is exactly the nodad address fcvm installs, and
/// that the guest has working egress.
///
/// The nodad/tentative checks are anchored to the EUI-64 link-local computed from
/// the veth's MAC — the address fcvm installs and the namespace's default route
/// points at — so an autogenerated address (EUI-64 without nodad, or stable-privacy
/// at some other address) can never satisfy them.
#[cfg(feature = "privileged-tests")]
async fn assert_routed_clone_nexthop_nodad_and_egress(
    clone_pid: u32,
    host_ipv6: &str,
    port: u16,
) -> Result<()> {
    let host_veth = common::get_network_field(clone_pid, "host_veth")
        .await
        .context("routed clone recorded no host_veth")?;
    let namespace = common::get_network_field(clone_pid, "namespace_name")
        .await
        .context("routed clone recorded no namespace_name")?;
    println!("  clone host_veth={} namespace={}", host_veth, namespace);

    // 1. The nexthop address — the EUI-64 link-local the namespace's default route
    //    points at — must exist, carry the `nodad` flag (only fcvm's explicit add
    //    sets it; the kernel never autogenerates with it), and not be tentative.
    let expected_ll = eui64_link_local(&host_veth).await?;
    let addr = tokio::process::Command::new("ip")
        .args(["-6", "addr", "show", "dev", &host_veth, "scope", "link"])
        .output()
        .await
        .context("reading host veth link-local")?;
    let addr = String::from_utf8_lossy(&addr.stdout);
    let ll_line = addr
        .lines()
        .find(|line| {
            line.trim_start()
                .strip_prefix("inet6 ")
                .and_then(|rest| rest.split('/').next())
                .and_then(|a| a.parse::<std::net::Ipv6Addr>().ok())
                == Some(expected_ll)
        })
        .with_context(|| {
            format!(
                "host veth {} does not hold {} — the guest's IPv6 nexthop does not exist:\n{}",
                host_veth, expected_ll, addr
            )
        })?;
    assert!(
        ll_line.contains("nodad"),
        "host veth {} link-local {} lacks the nodad flag, so the kernel autogenerated \
         it and ran DAD on it — the guest's IPv6 nexthop is unusable for 1-2s:\n{}",
        host_veth,
        expected_ll,
        addr
    );
    assert!(
        !ll_line.contains("tentative"),
        "host veth {} link-local {} is still tentative — it cannot answer Neighbor \
         Solicitations, so the guest has no egress:\n{}",
        host_veth,
        expected_ll,
        addr
    );
    println!(
        "  ✓ nexthop {} is present, nodad, and not tentative",
        expected_ll
    );

    // 2. Nothing inside the namespace may be tentative either: br0's link-local is
    //    the source address for the NS that resolves the nexthop.
    let ns_addr = tokio::process::Command::new("ip")
        .args(["netns", "exec", &namespace, "ip", "-6", "addr", "show"])
        .output()
        .await
        .context("reading namespace IPv6 addresses")?;
    let ns_addr = String::from_utf8_lossy(&ns_addr.stdout);
    assert!(
        !ns_addr.contains("tentative"),
        "namespace {} still has tentative IPv6 addresses, so it cannot source a \
         Neighbor Solicitation for the nexthop:\n{}",
        namespace,
        ns_addr
    );
    println!("  ✓ no tentative addresses in the clone namespace");

    // 3. End-to-end: the guest must reach the host over the routed path. This is a
    //    functional egress check, NOT a DAD-stall catcher — by the time `fcvm exec`
    //    can run, any DAD window has long expired, so no wall-clock bound measured
    //    from here could catch the stall (assertion 1 above is the catcher). Each
    //    attempt is capped at 50ms by `timeout`: bash's /dev/tcp has no connect
    //    timeout of its own, so a black-holed SYN would otherwise block for the
    //    kernel's full ~130s retry sequence and this test would hang instead of
    //    failing.
    let script = format!(
        r#"deadline=$((SECONDS+15))
while :; do
  if timeout 0.05 bash -c "exec 3<>/dev/tcp/{host}/{port}" 2>/dev/null; then echo NETRDY_OK; exit 0; fi
  if [ "$SECONDS" -ge "$deadline" ]; then echo NETRDY_FAIL; exit 1; fi
done"#,
        host = host_ipv6,
        port = port
    );
    let probe = tokio::process::Command::new(common::find_fcvm_binary()?)
        .args([
            "exec",
            "--pid",
            &clone_pid.to_string(),
            "--vm",
            "--",
            "bash",
            "-c",
            &script,
        ])
        .output()
        .await
        .context("running in-guest connect probe")?;
    let out = String::from_utf8_lossy(&probe.stdout);
    assert!(
        out.lines().any(|l| l.trim() == "NETRDY_OK"),
        "guest could not reach [{}]:{} over routed IPv6 within 15s \
         (stdout={:?}, stderr={:?})",
        host_ipv6,
        port,
        out.trim(),
        String::from_utf8_lossy(&probe.stderr).trim()
    );
    println!("  ✓ guest egress works");
    Ok(())
}

/// A private (ULA) prefix no test host routes to itself. A clone restored under it
/// needs no traffic beyond this host: it restores with its container running, and its
/// egress check talks to a server on the host.
#[cfg(feature = "privileged-tests")]
const RESTORE_PREFIX: &str = "fd5a:fc7a:1079::/112";

/// Whether `addr` lies inside the CIDR `prefix`.
#[cfg(feature = "privileged-tests")]
fn inside_prefix(addr: &str, prefix: &str) -> Result<bool> {
    let (net, len) = prefix
        .split_once('/')
        .with_context(|| format!("{prefix} has no length"))?;
    let len: u32 = len.parse().with_context(|| format!("length of {prefix}"))?;
    anyhow::ensure!((1..=128).contains(&len), "length of {prefix} out of range");
    let net = u128::from(net.parse::<std::net::Ipv6Addr>()?);
    let bits = u128::from(
        addr.parse::<std::net::Ipv6Addr>()
            .with_context(|| format!("parsing {addr}"))?,
    );
    Ok(bits >> (128 - len) == net >> (128 - len))
}

/// #1079: a routed clone restored with `--ipv6-prefix` takes its address from that
/// prefix, not from the one its snapshot was created under. Without it, a host whose
/// routed prefix changed since the snapshot, or another host, gives the clone an
/// address its network does not route back to the host.
///
/// The baseline runs under the host's own routed setup (FCVM_IPV6_PREFIX, or the /64
/// routed mode detects), and the clone is restored under RESTORE_PREFIX, which holds
/// none of the host's addresses. A restore that ignored the given prefix would put the
/// clone back inside the host's prefix, outside RESTORE_PREFIX. The clone's address is
/// checked as fcvm records it, as the host routes and proxies it, and as the guest holds
/// it on eth0; its egress goes to a server on this host.
#[cfg(feature = "privileged-tests")]
#[tokio::test]
async fn test_egress_clone_routed_takes_the_restore_prefix() -> Result<()> {
    let (baseline_name, clone_name, snapshot_name, _) =
        common::unique_names("egress-routed-prefix");

    let test_server = common::LocalTestServer::start_on_available_port("::")
        .await
        .context("starting local test server")?;
    // Every VM process still running when the body returns, killed afterwards whatever
    // the outcome.
    let mut running: Vec<u32> = Vec::new();
    let result = async {
        let egress_url = get_egress_url("routed", test_server.port).await?;
        let fcvm_path = common::find_fcvm_binary()?;
        let (_baseline_child, baseline_pid) = common::spawn_fcvm_with_logs(
            &[
                "podman",
                "run",
                "--name",
                &baseline_name,
                "--network",
                "routed",
                common::TEST_IMAGE,
            ],
            &baseline_name,
        )
        .await
        .context("spawning baseline VM")?;
        running.push(baseline_pid);
        common::poll_health_by_pid(baseline_pid, 300)
            .await
            .context("baseline VM failed to become healthy")?;
        let baseline_ipv6 = guest_ipv6(baseline_pid).await?;
        anyhow::ensure!(
            !inside_prefix(&baseline_ipv6, RESTORE_PREFIX)?,
            "control: the baseline's address {baseline_ipv6} is already inside {RESTORE_PREFIX}"
        );
        let snap = tokio::process::Command::new(&fcvm_path)
            .args([
                "snapshot",
                "create",
                "--pid",
                &baseline_pid.to_string(),
                "--tag",
                &snapshot_name,
            ])
            .output()
            .await
            .context("running snapshot create")?;
        anyhow::ensure!(
            snap.status.success(),
            "snapshot creation failed: {}",
            String::from_utf8_lossy(&snap.stderr)
        );
        common::kill_process(baseline_pid).await;
        running.retain(|pid| *pid != baseline_pid);

        let (_serve_child, serve_pid) = common::spawn_fcvm_with_logs(
            &["snapshot", "serve", &snapshot_name],
            "uffd-server-prefix",
        )
        .await
        .context("spawning memory server")?;
        running.push(serve_pid);
        common::poll_serve_state_by_pid(serve_pid, 30).await?;
        let (_clone_child, clone_pid) = common::spawn_fcvm_with_logs(
            &[
                "snapshot",
                "run",
                "--pid",
                &serve_pid.to_string(),
                "--name",
                &clone_name,
                "--ipv6-prefix",
                RESTORE_PREFIX,
            ],
            &clone_name,
        )
        .await
        .context("spawning clone")?;
        running.push(clone_pid);
        common::poll_health_by_pid(clone_pid, 120).await?;

        let clone_ipv6 = guest_ipv6(clone_pid).await?;
        println!(
            "  baseline address {baseline_ipv6}, clone address {clone_ipv6}, restore prefix {RESTORE_PREFIX}"
        );
        anyhow::ensure!(
            inside_prefix(&clone_ipv6, RESTORE_PREFIX)?,
            "the clone's address {clone_ipv6} is outside {RESTORE_PREFIX}, the prefix it was \
             restored under (the baseline ran at {baseline_ipv6})"
        );
        let clone_veth = common::get_network_field(clone_pid, "host_veth")
            .await
            .context("the routed clone recorded no host_veth")?;
        let route = host_ip(&["-6", "route", "show", &format!("{clone_ipv6}/128")]).await?;
        anyhow::ensure!(
            route.split_whitespace().any(|word| word == clone_veth),
            "the host does not route the clone's address {clone_ipv6} through its veth {clone_veth}: {}",
            route.trim()
        );
        let proxy = host_ip(&["-6", "neigh", "show", "proxy"]).await?;
        anyhow::ensure!(
            proxy
                .lines()
                .any(|line| line.split_whitespace().next() == Some(clone_ipv6.as_str())),
            "the host has no proxy-NDP entry for the clone's address {clone_ipv6}:\n{proxy}"
        );
        let eth0 = common::exec_in_vm(
            clone_pid,
            &["PATH=/usr/sbin:/usr/bin:/sbin:/bin ip -6 addr show dev eth0 scope global"],
        )
        .await
        .context("reading the guest's eth0 addresses")?;
        anyhow::ensure!(
            eth0.contains(&format!("inet6 {clone_ipv6}/")),
            "the guest's eth0 does not hold the clone's address {clone_ipv6}:\n{eth0}"
        );
        anyhow::ensure!(
            !eth0.contains(&format!("inet6 {baseline_ipv6}/")),
            "the guest's eth0 still holds the snapshot's address {baseline_ipv6}:\n{eth0}"
        );
        test_egress(&fcvm_path, clone_pid, &egress_url).await
    }
    .await;

    for pid in running.into_iter().rev() {
        common::kill_process(pid).await;
    }
    test_server.stop().await;
    result
}

/// Wait until a run's log says how it used the snapshot cache, so a cold boot shows in
/// seconds rather than after a health timeout.
#[cfg(feature = "privileged-tests")]
async fn wait_for_cache_choice(
    log: &std::path::Path,
    limit: Duration,
) -> Result<(&'static str, String)> {
    let deadline = std::time::Instant::now() + limit;
    loop {
        if let Some(choice) = common::cache_choice(log) {
            return Ok(choice);
        }
        anyhow::ensure!(
            std::time::Instant::now() < deadline,
            "{} names no cache choice after {limit:?}",
            log.display()
        );
        tokio::time::sleep(Duration::from_millis(500)).await;
    }
}

/// #1079: a routed run under a new IPv6 prefix reuses the snapshot a run under the
/// host's own prefix left, and its VM takes its address from the new prefix. The prefix
/// is in no snapshot key because the restore takes the run's prefix.
///
/// The second run uses RESTORE_PREFIX, which holds none of the host's addresses, so it
/// works only as a restore: a cold boot under it could not pull its image.
#[cfg(feature = "privileged-tests")]
#[tokio::test]
async fn test_routed_run_under_a_new_prefix_reuses_its_snapshot() -> Result<()> {
    let (first_name, second_name, _, _) = common::unique_names("routed-prefix-cache");
    let env_unique = format!("PREFIXCACHE_ID={first_name}");
    let test_server = common::LocalTestServer::start_on_available_port("::")
        .await
        .context("starting local test server")?;
    // VM processes still running and snapshot keys made, cleaned up whatever the outcome.
    let mut running: Vec<u32> = Vec::new();
    let mut keys: Vec<String> = Vec::new();
    let result = async {
        let egress_url = get_egress_url("routed", test_server.port).await?;
        let fcvm_path = common::find_fcvm_binary()?;

        let (_first_child, first_pid, first_log) =
            common::spawn_fcvm_snapshots_enabled_with_env_and_log_path(
                &[
                    "podman",
                    "run",
                    "--name",
                    &first_name,
                    "--network",
                    "routed",
                    "--env",
                    &env_unique,
                    common::TEST_IMAGE,
                ],
                &[],
            )
            .await
            .context("spawning the first run")?;
        running.push(first_pid);
        common::poll_health_by_pid(first_pid, 300)
            .await
            .context("the first run never turned healthy")?;
        common::kill_process(first_pid).await;
        running.retain(|pid| *pid != first_pid);
        let (first_how, first_key) = common::cache_choice(&first_log)
            .context("the first run's log has no line that says how it started")?;
        keys.push(first_key.clone());
        anyhow::ensure!(
            first_how == "cold boot",
            "control: the first run starts from a cold cache and started from a {first_how}"
        );

        let (_second_child, second_pid, second_log) =
            common::spawn_fcvm_snapshots_enabled_with_env_and_log_path(
                &[
                    "podman",
                    "run",
                    "--name",
                    &second_name,
                    "--network",
                    "routed",
                    "--ipv6-prefix",
                    RESTORE_PREFIX,
                    "--env",
                    &env_unique,
                    common::TEST_IMAGE,
                ],
                &[],
            )
            .await
            .context("spawning the second run")?;
        running.push(second_pid);
        let (second_how, second_key) =
            wait_for_cache_choice(&second_log, Duration::from_secs(60)).await?;
        if second_key != first_key {
            keys.push(second_key.clone());
        }
        anyhow::ensure!(
            second_how != "cold boot",
            "the run under {RESTORE_PREFIX} cold-booted instead of reusing the snapshot of the run \
             under the host's own prefix"
        );
        anyhow::ensure!(
            second_key == first_key,
            "the two runs keyed their snapshots differently: {first_key} and {second_key}"
        );
        common::poll_health_by_pid(second_pid, 300)
            .await
            .context("the second run never turned healthy")?;
        let address = guest_ipv6(second_pid).await?;
        anyhow::ensure!(
            inside_prefix(&address, RESTORE_PREFIX)?,
            "the second run's address {address} is outside {RESTORE_PREFIX}, the prefix it ran under"
        );
        let eth0 = common::exec_in_vm(
            second_pid,
            &["PATH=/usr/sbin:/usr/bin:/sbin:/bin ip -6 addr show dev eth0 scope global"],
        )
        .await
        .context("reading the guest's eth0 addresses")?;
        anyhow::ensure!(
            eth0.contains(&format!("inet6 {address}/")),
            "the guest's eth0 does not hold {address}:\n{eth0}"
        );
        test_egress(&fcvm_path, second_pid, &egress_url).await
    }
    .await;

    for pid in running.into_iter().rev() {
        common::kill_process(pid).await;
    }
    test_server.stop().await;
    for key in keys {
        for snapshot in [
            fcvm::commands::podman::startup_snapshot_key(
                &key,
                None,
                None,
                fcvm::commands::podman::host_proxy_identity().as_deref(),
            ),
            key.clone(),
        ] {
            if common::snapshot_exists(&snapshot) {
                if let Err(error) = common::delete_snapshot(&snapshot).await {
                    println!("  could not delete snapshot {snapshot}: {error:#}");
                }
            }
        }
    }
    result
}

/// Output of `ip ARGS` on the host.
#[cfg(feature = "privileged-tests")]
async fn host_ip(args: &[&str]) -> Result<String> {
    let output = tokio::process::Command::new("ip")
        .args(args)
        .output()
        .await
        .with_context(|| format!("running ip {args:?}"))?;
    anyhow::ensure!(
        output.status.success(),
        "ip {args:?} failed: {}",
        String::from_utf8_lossy(&output.stderr).trim()
    );
    Ok(String::from_utf8_lossy(&output.stdout).into_owned())
}

/// The guest IPv6 address fcvm recorded for a routed VM, without its /128.
#[cfg(feature = "privileged-tests")]
async fn guest_ipv6(pid: u32) -> Result<String> {
    let recorded = common::get_network_field(pid, "guest_ipv6").await?;
    Ok(recorded.split('/').next().unwrap_or_default().to_string())
}

/// Compute the EUI-64 link-local for an interface from its MAC, independently of
/// fcvm's own computation, so the nexthop assertion cross-checks fcvm's result.
#[cfg(feature = "privileged-tests")]
async fn eui64_link_local(iface: &str) -> Result<std::net::Ipv6Addr> {
    let out = tokio::process::Command::new("ip")
        .args(["-j", "link", "show", "dev", iface])
        .output()
        .await
        .context("running `ip -j link show`")?;
    anyhow::ensure!(
        out.status.success(),
        "`ip -j link show dev {}` failed: {}",
        iface,
        String::from_utf8_lossy(&out.stderr).trim()
    );
    let links: Vec<serde_json::Value> =
        serde_json::from_slice(&out.stdout).context("parsing `ip -j link show` JSON")?;
    let mac = links
        .first()
        .and_then(|l| l.get("address"))
        .and_then(|a| a.as_str())
        .with_context(|| format!("no MAC address for {}", iface))?;
    let bytes = mac
        .split(':')
        .map(|h| u8::from_str_radix(h, 16))
        .collect::<Result<Vec<u8>, _>>()
        .with_context(|| format!("unparseable MAC {:?} on {}", mac, iface))?;
    anyhow::ensure!(
        bytes.len() == 6,
        "MAC {:?} on {} is not 6 octets",
        mac,
        iface
    );
    // EUI-64: flip the universal/local bit of the first octet, insert ff:fe.
    format!(
        "fe80::{:02x}{:02x}:{:02x}ff:fe{:02x}:{:02x}{:02x}",
        bytes[0] ^ 0x02,
        bytes[1],
        bytes[2],
        bytes[3],
        bytes[4],
        bytes[5]
    )
    .parse()
    .context("parsing computed EUI-64 link-local")
}

/// Calculate the URL a VM should use to reach a test server on the host
async fn get_egress_url(network: &str, port: u16) -> Result<String> {
    match network {
        "rootless" => {
            // For rootless, pasta gateway is 10.0.2.2
            Ok(format!("http://10.0.2.2:{}/", port))
        }
        "bridged" => {
            // For bridged, use host's primary IPv4 (reachable via CONNMARK routing)
            let host_ip = common::get_host_primary_ip().await?;
            Ok(format!("http://{}:{}/", host_ip, port))
        }
        "routed" => {
            // For routed, use host's IPv6. Each clone has a unique IPv6,
            // so return routing works naturally (no CONNMARK needed).
            let host_ipv6 = common::get_host_ipv6().await?;
            Ok(format!("http://[{}]:{}/", host_ipv6, port))
        }
        _ => anyhow::bail!("Unknown network type: {}", network),
    }
}

