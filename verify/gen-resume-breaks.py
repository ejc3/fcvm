#!/usr/bin/env python3
"""Regenerate the recorded runs from the search's output on stdin.

    lake exe resume-breaks traces          | ./gen-resume-breaks.py           > ResumeVerify/Breaks.lean
    lake exe resume-breaks mutants traces  | ./gen-resume-breaks.py mutants   > ResumeVerify/MutantBreaks.lean

Each run the search prints becomes a theorem checked by `decide`: the run is possible under
the rule book named and ends in a state the test flags. For today's rule books a second
theorem replays the same labels under the repaired VMM and requires every test to pass at the
end. For a mutant the second theorem is that the mutant is not `Sound`.
"""
import re
import sys

BOOK = {
    "cloud-hypervisor": ("Today.cloudHypervisor", "ch", "Design.cloudHypervisor"),
    "cloud-hypervisor-repin": ("Today.cloudHypervisorRepin", "repin", "Design.cloudHypervisor"),
    "cloud-hypervisor-upstream-preserve": ("(Today.cloudHypervisorUpstream false)", "upstreamPreserve", "Design.cloudHypervisor"),
    "cloud-hypervisor-upstream-advance": ("(Today.cloudHypervisorUpstream true)", "upstreamAdvance", "Design.cloudHypervisor"),
    "fork-default": ("Today.forkDefault", "fork", "Design.firecracker"),
    "fork-before-630": ("Today.forkBefore630", "before630", "Design.firecracker"),
    "fork-nested": ("Today.forkNested", "nested", "Design.firecracker"),
}
CFG = {"plain": "plain", "level": "level", "offline": "offline", "dump": "dump", "lags": "lags",
       "nv-dump": "nvDump", "nv-l2": "nvL2", "nv-lags": "nvLags"}
CHECK = {"lostDeviceIrq": "lostDeviceIrq C", "spins": "spins C", "timerLoops": "timerLoops C"}
MUTANTS = len(sys.argv) > 1 and sys.argv[1] == "mutants"


def mutant_id(name):
    parts = name.split("-")[1:]
    return parts[0] + "".join(p[:1].upper() + p[1:] for p in parts[1:])


if MUTANTS:
    out = ['''import ResumeVerify.Mutants
import ResumeVerify.Proofs

/-!
# Every mutant has a break, and so is not sound

Generated by `gen-resume-breaks.py mutants` from `lake exe resume-breaks mutants traces`: do not
edit by hand. For each rule book of `Mutants.lean`, a shortest run to a break, replayed and
checked by `decide`, and from the same run that the mutant is not `Sound`.
-/

namespace Resume

set_option maxRecDepth 100000
''']
else:
    out = ['''import ResumeVerify.Spec
import ResumeVerify.Today
import ResumeVerify.Design
import ResumeVerify.Properties
import ResumeVerify.Configs

/-!
# Every break the search found, as a fact the kernel checks

Generated by `gen-resume-breaks.py` from `lake exe resume-breaks traces`: do not edit by hand.
Each `breaks_*` theorem replays a shortest run under the rule book named and evaluates the test
at its end. Each `design_keeps_*` theorem replays the same labels under the repaired VMM, as
far as they are possible there (a step that the break needed may not be), and evaluates every
test where the run stops; the theorems of `Proofs.lean`, not these, are the evidence for the
design.
-/

namespace Resume

set_option maxRecDepth 100000
''']
title = None
steps = []
count = 0
for line in sys.stdin:
    m = re.match(r"### ([\w-]+), ([\w-]+): (R\d) (\w+) \((\d+) steps\)", line)
    if m:
        title = m.groups()
        steps = []
        continue
    m = re.match(r"  \d+\. (.*)", line)
    if m and title:
        steps.append(m.group(1))
        continue
    m = re.match(r"  => (.*)", line)
    if m and title:
        end = m.group(1)
        continue
    m = re.match(r"  \[(.*)\]$", line)
    if m and title:
        cfg, book, req, check, n = title
        c = f"Cfg.{CFG[cfg]}"
        test = CHECK.get(check, check).replace(" C", f" {c}")
        if MUTANTS:
            mid = mutant_id(book)
            out.append(f"/-- {req} {check}, `{book}` in `{cfg}`, {n} steps:\n")
            for i, s in enumerate(steps, 1):
                out.append(f"{i}. {s}\n")
            out.append(f"\nEnds in: {end} -/\n")
            out.append(f"def MutantRun.{mid} : List Label :=\n  [{m.group(1)}]\n\n")
            out.append(f"theorem mutant_{mid}_breaks :\n    (replay Mutant.{mid} {c} MutantRun.{mid} (init {c})).map ({test}) = some true := by\n  decide\n\n")
            out.append(f"theorem mutant_{mid}_not_sound : ¬ Sound Mutant.{mid} :=\n  not_sound_of_run (C := {c}) (run := MutantRun.{mid}) (by decide)\n\n")
        else:
            today, short, design = BOOK[book]
            name = f"{short}_{CFG[cfg]}_{check}"
            out.append(f"/-- {req}, `{book}` in `{cfg}`, {n} steps:\n")
            for i, s in enumerate(steps, 1):
                out.append(f"{i}. {s}\n")
            out.append(f"\nEnds in: {end} -/\n")
            out.append(f"def Run.{name} : List Label :=\n  [{m.group(1)}]\n\n")
            out.append(f"theorem breaks_{name} :\n    (replay {today} {c} Run.{name} (init {c})).map ({test}) = some true := by\n  decide\n\n")
            out.append(f"theorem design_keeps_{name} :\n    healthy {c} (replayWhile {design} {c} Run.{name} (init {c})) = true := by\n  decide\n\n")
        count += 1
        title = None
out.append("end Resume\n")
sys.stdout.write("".join(out))
sys.stderr.write(f"{count} runs\n")
