#!/usr/bin/env python3
"""Regenerate ResumeVerify/Breaks.lean from `lake exe resume-breaks traces` on stdin.

Each run the search prints becomes a theorem checked by `decide`: the run is possible under
the rule book named and ends in a state the test flags. A second theorem replays the same
labels under the repaired VMM and requires every test to pass at the end.
"""
import re
import sys

BOOK = {
    "cloud-hypervisor": ("Today.cloudHypervisor", "ch", "Design.cloudHypervisor"),
    "cloud-hypervisor-repin": ("Today.cloudHypervisorRepin", "repin", "Design.cloudHypervisor"),
    "fork-default": ("Today.forkDefault", "fork", "Design.firecracker"),
    "fork-before-630": ("Today.forkBefore630", "before630", "Design.firecracker"),
    "fork-nested": ("Today.forkNested", "nested", "Design.firecracker"),
}
CFG = {"plain": "plain", "level": "level", "offline": "offline", "dump": "dump", "lags": "lags",
       "nv-dump": "nvDump", "nv-l2": "nvL2", "nv-lags": "nvLags"}
CHECK = {"lostDeviceIrq": "lostDeviceIrq C", "spins": "spins C"}

out = ['''import ResumeVerify.Spec
import ResumeVerify.Today
import ResumeVerify.Design
import ResumeVerify.Properties
import ResumeVerify.Configs

/-!
# Every break the search found, as a fact the kernel checks

Generated by `gen-resume-breaks.py` from `lake exe resume-breaks traces`: do not edit by hand.
Each `breaks_*` theorem replays a shortest run under the rule book named and evaluates the test
at its end. Each `design_keeps_*` theorem replays the same labels under the repaired VMM and
evaluates every test at the end of the run; the theorems of `Proofs.lean`, not these, are the
evidence for the design.
-/

namespace Resume

set_option maxRecDepth 100000
''']
title = None
steps = []
count = 0
for line in sys.stdin:
    m = re.match(r"### ([\w-]+), ([\w-]+): (R\d) (\w+) \((\d+) steps\)", line)
    if m:
        title = m.groups()
        steps = []
        continue
    m = re.match(r"  \d+\. (.*)", line)
    if m and title:
        steps.append(m.group(1))
        continue
    m = re.match(r"  => (.*)", line)
    if m and title:
        end = m.group(1)
        continue
    m = re.match(r"  \[(.*)\]$", line)
    if m and title:
        cfg, book, req, check, n = title
        today, short, design = BOOK[book]
        name = f"{short}_{CFG[cfg]}_{check}"
        test = CHECK.get(check, check).replace(" C", f" Cfg.{CFG[cfg]}")
        out.append(f"/-- {req}, `{book}` in `{cfg}`, {n} steps:\n")
        for i, s in enumerate(steps, 1):
            out.append(f"{i}. {s}\n")
        out.append(f"\nEnds in: {end} -/\n")
        out.append(f"def Run.{name} : List Label :=\n  [{m.group(1)}]\n\n")
        out.append(f"theorem breaks_{name} :\n    (replay {today} Cfg.{CFG[cfg]} Run.{name} (init Cfg.{CFG[cfg]})).map ({test}) = some true := by\n  decide\n\n")
        out.append(f"theorem design_keeps_{name} :\n    (replay {design} Cfg.{CFG[cfg]} Run.{name} (init Cfg.{CFG[cfg]})).map (healthy Cfg.{CFG[cfg]}) = some true := by\n  decide\n\n")
        count += 1
        title = None
out.append("end Resume\n")
sys.stdout.write("".join(out))
sys.stderr.write(f"{count} runs\n")
